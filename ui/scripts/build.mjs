// Production build: compiles Tailwind, concatenates the AngularJS sources (in
// index.html order) plus a $templateCache of every *.template.html into one
// content-hashed bundle, and copies static assets and vendor scripts into dist/.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { VENDOR_FILES } from './vendor.mjs';

const root = resolve(fileURLToPath(import.meta.url), '../..');
const src = join(root, 'src');
const dist = join(root, 'dist');

const hash = content => createHash('sha256').update(content).digest('hex').slice(0, 10);

rmSync(dist, { recursive: true, force: true });
mkdirSync(join(dist, 'vendor'), { recursive: true });

cpSync(join(root, 'public'), dist, { recursive: true });

for (const [name, from] of Object.entries(VENDOR_FILES)) {
  cpSync(join(root, from), join(dist, 'vendor', name));
}

// Tailwind scans src/ for class names (including the *.template.html files).
const cssTmp = join(dist, 'app.css');
execFileSync(join(root, 'node_modules/.bin/tailwindcss'),
  ['-i', join(src, 'styles.css'), '-o', cssTmp, '--minify'],
  { cwd: root, stdio: 'inherit' });
const css = readFileSync(cssTmp);
const cssName = `app.${hash(css)}.css`;
rmSync(cssTmp);
writeFileSync(join(dist, cssName), css);

let html = readFileSync(join(src, 'index.html'), 'utf8');

const jsBlock = html.match(/<!-- build:js -->([\s\S]*?)<!-- \/build:js -->/);
const scripts = [...jsBlock[1].matchAll(/<script src="\/(app\/[^"]+)"><\/script>/g)].map(m => m[1]);
// Pre-load every component template into $templateCache under the same path its
// templateUrl uses, so production never fetches template HTML at runtime.
const templates = readdirSync(join(src, 'app'), { recursive: true })
  .filter(file => file.endsWith('.template.html'))
  .sort()
  .map(file => `app/${file.split(sep).join('/')}`);
const templateCache = `// $templateCache (generated by scripts/build.mjs)
angular.module('quillingApp').run(['$templateCache', function ($templateCache) {
${templates.map(url => `  $templateCache.put(${JSON.stringify(url)}, ${JSON.stringify(readFileSync(join(src, url), 'utf8'))});`).join('\n')}
}]);
`;

const js = scripts.map(file => `// ${file}\n${readFileSync(join(src, file), 'utf8')}`).join('\n') + '\n' + templateCache;
const jsName = `app.${hash(js)}.js`;
writeFileSync(join(dist, jsName), js);

html = html
  .replace(jsBlock[0], `<script src="/${jsName}"></script>`)
  .replace(/<!-- build:css -->[\s\S]*?<!-- \/build:css -->/, `<link rel="stylesheet" href="/${cssName}" />`);
writeFileSync(join(dist, 'index.html'), html);

console.log(`Built dist/: ${scripts.length} app scripts -> ${jsName}, ${cssName}`);
